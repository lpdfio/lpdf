// The table of counts/SUMMARY.md in lpdf-bench: one row for each release that has a counts/vX.Y.Z.json,
// to see how the instructions, allocations and memory of the core moved from release to release.
// bench.yml's history job writes it after it has saved the counts of a release. Nobody edits it.
//
// Usage: node scripts/bench-counts-summary.mjs [--markdown <file>] <counts folder>

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { FIXTURES, STAGES } from './bench-counts-report.mjs';

/** The fixtures whose quantities the table shows, a small one and the largest. */
export const SHOWN_FIXTURES = ['m', 'xl'];

const RELEASE_FILE = /^v\d+\.\d+\.\d+\.json$/;

const versionParts = version => version.slice(1).split('.').map(Number);

/** Orders `vX.Y.Z` by number, so v0.10.0 comes after v0.9.0. */
export function compareVersions(a, b) {
    const [pa, pb] = [versionParts(a), versionParts(b)];
    return pa[0] - pb[0] || pa[1] - pb[1] || pa[2] - pb[2];
}

/** The releases of a folder, oldest first: what bench.yml saved in each `vX.Y.Z.json`. */
export function readReleases(folder) {
    return readdirSync(folder)
        .filter(file => RELEASE_FILE.test(file))
        .map(file => JSON.parse(readFileSync(path.join(folder, file), 'utf8')))
        .sort((a, b) => compareVersions(a.version, b.version));
}

/**
 * How many times the instructions of a stage grew from the release before to this one: the geometric
 * mean of the ratios of the fixtures, so a small fixture counts as much as a large one. Undefined when
 * either build lacks the stage.
 */
export function step(release, stage) {
    const ratios = FIXTURES.flatMap(fixture => {
        const after = release.counts?.[fixture]?.[stage]?.instructions;
        const before = release.against?.counts?.[fixture]?.[stage]?.instructions;
        return after > 0 && before > 0 ? [after / before] : [];
    });
    if (ratios.length === 0) return undefined;
    return Math.exp(ratios.reduce((sum, ratio) => sum + Math.log(ratio), 0) / ratios.length);
}

/**
 * The rows of the table, oldest release first. A release that was measured has, for each stage it has,
 * the index of its instructions and the step that made it. The index is 100 at the first release with
 * the stage, and also where the release before lacks the stage, so there is no step to apply. `gap` is
 * the release a step is from when that is not the measured release before this one.
 */
export function summarize(releases) {
    const indexes = {};
    let previous;
    return releases.map(release => {
        if (!release.counts) return { release, stages: null };
        const stages = {};
        for (const { id } of STAGES) {
            if (!FIXTURES.some(fixture => release.counts[fixture]?.[id])) continue;
            const stepped = step(release, id);
            indexes[id] = stepped === undefined || indexes[id] === undefined ? 100 : indexes[id] * stepped;
            stages[id] = { index: indexes[id], step: stepped };
        }
        const gap = previous && release.against?.version !== previous ? release.against?.version ?? null : undefined;
        previous = release.version;
        return { release, stages, gap };
    });
}

const sign = (percent, text) => Number(text) === 0 ? '±' : percent > 0 ? '+' : '−';

function stageCell(stage) {
    if (!stage) return '—';
    if (stage.step === undefined) return stage.index.toFixed(1);
    const percent = (stage.step - 1) * 100;
    const text = Math.abs(percent).toFixed(1);
    return `${stage.index.toFixed(1)} (${sign(percent, text)}${text}%)`;
}

const MEMORY = [
    { title: 'Allocations', measure: 'allocations', format: n => n.toLocaleString('en-US') },
    { title: 'Bytes allocated', measure: 'bytes_allocated', format: n => (n / 1_000_000).toFixed(2) },
    { title: 'Peak memory', measure: 'peak_bytes', format: n => (n / 1_000_000).toFixed(2) },
];

/** `m / xl` of one measure of a whole render, or `—` when the release lacks it for either fixture. */
function memoryCell(release, { measure, format }) {
    const values = SHOWN_FIXTURES.map(fixture => release.counts[fixture]?.end_to_end?.[measure]);
    return values.every(v => v !== undefined) ? values.map(format).join(' / ') : '—';
}

/** The compiler of a release as `1.99.0`, from `rustc 1.99.0 (b940084d7 2026-09-28)`. */
const rustVersion = rust => rust ? /^rustc (\S+)/.exec(rust)?.[1] ?? rust : '—';

const code = version => `\`${version}\``;

/** The file in Markdown: how to read it, then a row for each release. */
export function markdown(rows) {
    const first = rows.find(r => r.stages)?.release;
    const shown = SHOWN_FIXTURES.join(' / ');
    const out = [
        '# Counts of each release',
        '',
        "Generated by lpdf's `bench.yml` from the `vX.Y.Z.json` files in this folder: don't edit it.",
        '',
        'The instruction columns are an index: 100 at the first release that has the stage, and each later release is ' +
            'the index of the one before times its step. A step is the geometric mean, over the fixtures xs, s, m, l and xl, ' +
            'of the release\'s instructions divided by those of the release before it, both measured in the same run. ' +
            '`110.3 (+4.2%)` is 10.3% more instructions than at the start and 4.2% more than at the release before.' +
            (first?.against ? ` The first row shows its step from ${first.against.version}, which has no file here.` : ''),
        '',
        `The other columns are the quantities of a whole render (end to end), for the fixtures ${SHOWN_FIXTURES.join(' and ')}, as \`${shown}\`. ` +
            'Peak memory is the heap when it is at its highest. MB = 1,000,000 bytes.',
        '',
        "A — is a number that release's file lacks: the stage had no benchmark yet, or the memory wasn't counted.",
        '',
        'The syntax changed in 0.26 and the fixtures in 0.27, so the steps of those two releases compare the same document ' +
            "written in each version's syntax and include what reading the new syntax costs. A release is measured on its own fixtures.",
        '',
    ];
    const measured = rows.filter(r => r.stages).map(r => r.release.version);
    for (const row of rows.filter(r => r.gap !== undefined)) {
        const before = measured[measured.indexOf(row.release.version) - 1];
        out.push(`The step of ${code(row.release.version)} is from ${row.gap ? code(row.gap) : 'a release'} that has no counts here: ` +
            `the index goes on from ${code(before)} without the steps between.`, '');
    }

    const headers = [
        'Release', ...STAGES.map(s => s.name[0].toUpperCase() + s.name.slice(1)),
        ...MEMORY.map(m => `${m.title} (${shown}${m.measure === 'allocations' ? '' : ', MB'})`), 'Rust',
    ];
    out.push(
        `| ${headers.join(' | ')} |`,
        `|${headers.map((_, i) => i === 0 || i === headers.length - 1 ? '---' : '---:').join('|')}|`,
    );
    for (const { release, stages } of rows) {
        const cells = stages
            ? [...STAGES.map(s => stageCell(stages[s.id])), ...MEMORY.map(m => memoryCell(release, m))]
            : ['not measured', ...Array(headers.length - 3).fill('—')];
        out.push(`| ${[release.version, ...cells, rustVersion(release.rust)].join(' | ')} |`);
    }
    out.push('');
    return out.join('\n');
}

function usage(message) {
    console.error(`bench-counts-summary: ${message}`);
    console.error('usage: node scripts/bench-counts-summary.mjs [--markdown <file>] <counts folder>');
    process.exit(2);
}

function main(args) {
    const folders = [];
    let markdownFile;
    for (let i = 0; i < args.length; i++) {
        if (args[i] === '--markdown') markdownFile = args[++i];
        else if (args[i].startsWith('--')) usage(`unknown option ${args[i]}`);
        else folders.push(args[i]);
    }
    if (folders.length !== 1) usage('give the counts folder');
    if (args.includes('--markdown') && !markdownFile) usage('--markdown takes a file');

    const releases = readReleases(folders[0]);
    if (releases.length === 0) usage(`${folders[0]} has no vX.Y.Z.json`);
    const report = markdown(summarize(releases));
    if (markdownFile) writeFileSync(markdownFile, report);
    else process.stdout.write(report);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    main(process.argv.slice(2));
}
